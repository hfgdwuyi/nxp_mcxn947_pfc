static void refreshLCD(void){
    if(sensor_status.powerDataUpdated) {
        Vin.integer = (int)Vrms.real;
        Vin.hundreds = Vin.integer / 100;
        Vin.tens = (Vin.integer % 100) / 10;
        Vin.units = (Vin.integer % 100) % 10;
        Vin.decimal = (int)((Vrms.real - Vin.integer) * 10);

        Iin.integer = (int)Irms.real;
        Iin.hundreds = Iin.integer / 100;
        Iin.tens = (Iin.integer % 100) / 10;
        Iin.units = (Iin.integer % 100) % 10;
        Iin.decimal = (int)((Irms.real - Iin.integer) * 10);

        VoutDisp.integer = (int)Vout.real;
        VoutDisp.hundreds = VoutDisp.integer / 100;
        VoutDisp.tens = (VoutDisp.integer % 100) / 10;
        VoutDisp.units = (VoutDisp.integer % 100) % 10;
        VoutDisp.decimal = (int)((Vout.real - VoutDisp.integer) * 10);

        IoutDisp.integer = (int)Iout.real;
        IoutDisp.hundreds = IoutDisp.integer / 100;
        IoutDisp.tens = (IoutDisp.integer % 100) / 10;
        IoutDisp.units = (IoutDisp.integer % 100) % 10;
        IoutDisp.decimal = (int)((Iout.real - IoutDisp.integer) * 10);

        switch (currentPage) {
        case PAGE_MAIN:
            clear_screen();
            showElectricalParameters();
            break;

        case PAGE_ENABLE_OUTPUT1:
            clear_screen();
            if (currentValue > 1)
                currentValue = 0;
            showEnableOutput1();
            if (isConfirm) {
                if (currentValue)
                    GPIO_PortSet(DCDC1_EN_GPIO, 1u << DCDC1_EN_GPIO_PIN);
            }
            break;

        case PAGE_ENABLE_OUTPUT2:
            clear_screen();
            if (currentValue > 1)
                currentValue = 0;
            showEnableOutput2();
            if (isConfirm) {
                if (currentValue)
                    GPIO_PortSet(DCDC2_EN_GPIO, 1u << DCDC2_EN_GPIO_PIN);
            }
            break;

        case PAGE_ADJUST_VOLTAGE1:
            clear_screen();
            showAdjustVoltage1();
            break;

        case PAGE_ADJUST_VOLTAGE2:
            clear_screen();
            showAdjustVoltage2();
            break;

        default:
            break;
        }
        sensor_status.powerDataUpdated = false;
    }
}
