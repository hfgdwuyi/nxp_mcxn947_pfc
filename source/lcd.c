void delay(uint16_t n_ms)
{
    vTaskDelay(pdMS_TO_TICKS(n_ms));
}

void transfer_command_lcd(uint8_t data1)
{
    char i;
    LCD_CS_LOW();
    LCD_RS_LOW();
    for(i=0;i<8;i++) {
        LCD_SCL_LOW();
        if(data1&0x80) LCD_SDA_HIGH();
        else LCD_SDA_LOW();
        LCD_SCL_HIGH();
        data1=data1<<1;
    }
    LCD_CS_HIGH();
}

void transfer_data_lcd(uint8_t data1)
{
    char i;
    LCD_CS_LOW();
    LCD_RS_HIGH();
    for(i=0;i<8;i++) {
        LCD_SCL_LOW();
        if(data1&0x80) LCD_SDA_HIGH();
        else LCD_SDA_LOW();
        LCD_SCL_HIGH();
        data1=data1<<1;
    }
    LCD_CS_HIGH();
}

void lcd_address(uint32_t page,uint32_t column)
{
    column=column-0x01;
    transfer_command_lcd(0xb0+page-1);
    transfer_command_lcd(0x10+(column>>4&0x0f));
    transfer_command_lcd(column&0x0f);
}

void display_graphic_5x8(uint8_t page,uint8_t column,uint8_t *dp)
{
    uint32_t i;
    lcd_address(page,column);
    for (i=0;i<6;i++) {
        transfer_data_lcd(*dp);
        dp++;
    }
}

void display_128x64(uint8_t *dp)
{
    uint8_t i,j;
    for(j=0;j<8;j++) {
        lcd_address(j+1,1);
        for (i=0;i<128;i++) {
            transfer_data_lcd(*dp);
            dp++;
        }
    }
}

void display_graphic_16x16(uint8_t page,uint8_t column,uint8_t *dp)
{
    uint8_t i,j;
    for(j=0;j<2;j++) {
        lcd_address(page+j,column);
        for (i=0;i<16;i++) {
            transfer_data_lcd(*dp);
            dp++;
        }
    }
}

