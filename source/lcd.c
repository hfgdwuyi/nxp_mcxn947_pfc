void Display(void)
{
	key_message_t msg;

	while (xQueueReceive(xKeyMessageQueue, &msg, 0) == pdTRUE) {
		switch (msg.type) {
			case MSG_INCREASE_PAGE:
				if(currentPage++ >= PAGE_COUNT)
					currentPage = 0;
				currentValue = 0;
				break;

			case MSG_DECREASE_PAGE:
				if(currentPage-- >= PAGE_COUNT)
					currentPage = PAGE_COUNT - 1;
				currentValue = 0;
				break;
				
			case MSG_INCREASE_VALUE:
				currentValue++;
				break;

			case MSG_DECREASE_VALUE:
				if(currentValue > 0)
					currentValue--;
				break;
				
			case MSG_CONFIRM:
				isConfirm = msg.confirm;
				msg.confirm = false;
				break;
				
			default:
				break;
		}
	}
	refreshLCD();

	
}

