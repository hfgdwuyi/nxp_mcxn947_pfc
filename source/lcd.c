/*******************************************************************************
 * Display task and page logic
 *******************************************************************************/

void prvDisplayTask(void *pvParameters)
{
    (void)pvParameters;
    TickType_t tick_start, tick_end, delay_target;

    lv_port_disp_init();

    for (;;) {
        tick_start = xTaskGetTickCount();

        Display();

        tick_end = xTaskGetTickCount();

        if (tick_end - tick_start >= pdMS_TO_TICKS(LV_DISP_DEF_REFR_PERIOD)) {
            delay_target = 1;
        } else {
            delay_target = pdMS_TO_TICKS(LV_DISP_DEF_REFR_PERIOD) - (tick_end - tick_start);
        }

        vTaskDelay(delay_target);
    }
}

void Display(void)
{
    key_message_t msg;

    while (xQueueReceive(xKeyMessageQueue, &msg, 0) == pdTRUE) {
        switch (msg.type) {
        case MSG_INCREASE_PAGE:
            currentPage++;
            if (currentPage >= PAGE_COUNT)
                currentPage = 0;
            currentValue = 0;
            break;

        case MSG_DECREASE_PAGE:
            if (currentPage == 0)
                currentPage = PAGE_COUNT - 1;
            else
                currentPage--;
            currentValue = 0;
            break;

        case MSG_INCREASE_VALUE:
            currentValue++;
            break;

        case MSG_DECREASE_VALUE:
            if (currentValue > 0)
                currentValue--;
            break;

        case MSG_CONFIRM:
            isConfirm = msg.confirm;
            msg.confirm = false;
            break;

        default:
            break;
        }
    }
    refreshLCD();
}

